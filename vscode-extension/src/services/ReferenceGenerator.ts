import * as vscode from 'vscode';
import { FilenameResolver } from './FilenameResolver';
import { LinkityAdapter } from '../core/LinkityAdapter';

const REFERENCE_MARKER_START = '<!-- linkity:references-start -->';
const REFERENCE_MARKER_END = '<!-- linkity:references-end -->';

export class ReferenceGenerator {
  private adapter = new LinkityAdapter();
  
  constructor(private resolver: FilenameResolver) {}
  
  async generateForDocument(document: vscode.TextDocument): Promise<void> {
    const text = document.getText();
    const links = this.adapter.extractAll(text);
    
    if (links.length === 0) {
      vscode.window.showInformationMessage('No wikilinks found in document');
      return;
    }
    
    // Check if auto-generated section exists
    const existingSection = this.findReferenceSection(text);
    const references = this.buildReferences(links, document.uri);
    
    if (references.length === 0) {
      vscode.window.showWarningMessage('No valid wikilinks to convert to references');
      return;
    }
    
    const referenceText = this.formatReferences(references);
    const edit = new vscode.WorkspaceEdit();
    
    if (existingSection) {
      // Replace existing section
      const range = new vscode.Range(
        document.positionAt(existingSection.start),
        document.positionAt(existingSection.end)
      );
      edit.replace(document.uri, range, referenceText);
    } else {
      // Append at end of document
      const lastLine = document.lineCount;
      const insertPosition = new vscode.Position(lastLine, 0);
      const insertText = text.endsWith('\n\n') ? referenceText : `\n\n${referenceText}`;
      edit.insert(document.uri, insertPosition, insertText);
    }
    
    await vscode.workspace.applyEdit(edit);
    vscode.window.showInformationMessage(`Generated ${references.length} reference(s)`);
  }
  
  private buildReferences(
    links: Array<{value: string; alias?: string; anchor?: string}>,
    sourceUri: vscode.Uri
  ): Array<{label: string; url: string}> {
    const references: Array<{label: string; url: string}> = [];
    const seen = new Set<string>();
    
    for (const link of links) {
      const uri = this.adapter.resolveLink(link, this.resolver, { sourceFileUri: sourceUri });
      if (!uri) {
        continue;
      }
      
      const label = link.alias || link.value || link.anchor || '';
      const url = link.anchor
        ? `${vscode.workspace.asRelativePath(uri)}#${link.anchor}`
        : vscode.workspace.asRelativePath(uri);
      
      // Deduplicate
      const key = `${label}:${url}`;
      if (seen.has(key)) {
        continue;
      }
      seen.add(key);
      
      references.push({ label, url });
    }
    
    return references;
  }
  
  private formatReferences(references: Array<{label: string; url: string}>): string {
    const lines = [REFERENCE_MARKER_START];
    
    for (const ref of references) {
      // URL encode spaces
      const encodedUrl = ref.url.replace(/ /g, '%20');
      lines.push(`[${ref.label}]: ${encodedUrl}`);
    }
    
    lines.push(REFERENCE_MARKER_END);
    
    return lines.join('\n');
  }
  
  private findReferenceSection(text: string): {start: number; end: number} | null {
    const startIndex = text.indexOf(REFERENCE_MARKER_START);
    if (startIndex === -1) {
      return null;
    }
    
    const endIndex = text.indexOf(REFERENCE_MARKER_END);
    if (endIndex === -1) {
      return null;
    }
    
    return {
      start: startIndex,
      end: endIndex + REFERENCE_MARKER_END.length
    };
  }
  
  isAutoGenerated(text: string): boolean {
    return text.includes(REFERENCE_MARKER_START);
  }
}
